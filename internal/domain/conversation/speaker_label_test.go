// labelCase は、self（応答を生成した Agent。空は mio。空白だけは「指定なし」）が生成した
// 応答 content から、先頭ラベルを取り除いた結果 want を表す。
type labelCase struct {
	name    string
	self    Speaker
	content string
	want    string
}

func TestStripLeadingSpeakerLabels(t *testing.T) {
	tests := []labelCase{
		// --- 判定の4例（生成した Agent 自身のラベルは区切りが無くても除去し、他のラベルは区切り必須）
		{name: "example: midori generation, glued self labels", self: SpeakerMidori, content: "[midori][midori] 本文", want: "本文"},
		{name: "example: shiro generation, doubled midori label", self: SpeakerShiro, content: "[midori] [midori] 本文", want: "本文"},
		{name: "example: mio generation, relay phrase of another agent stays", self: SpeakerMio, content: "[shiro]からの報告です", want: "[shiro]からの報告です"},
		{name: "example: mio generation, glued self label", self: SpeakerMio, content: "[mio]こんにちは", want: "こんにちは"},

		// --- 旧 Mio の回帰（自分のラベル）
		{name: "plain label", content: "[mio] こんにちは", want: "こんにちは"},
		{name: "case and colon", content: " [MIO]：こんにちは ", want: "こんにちは"},
		{name: "self label with ascii colon and spaces", content: "[mio] : こんにちは", want: "こんにちは"},
		{name: "self label glued, upper case", self: SpeakerMidori, content: "[MIDORI]本文", want: "本文"},
		{name: "self label glued then colon", content: "[mio]：こんにちは", want: "こんにちは"},
		{name: "self label glued, relay-like phrase is removed for the speaker itself", content: "[mio]は次のとおり答えました", want: "は次のとおり答えました"},
		{name: "self label before a no-break space", content: "[mio] 本文", want: "本文"},

		// --- 他の既知 Agent 名のラベルは、区切りがある場合とラベルだけの場合に限って除去
		{name: "other label with a space", content: "[midori] こんにちは", want: "こんにちは"},
		{name: "other label with ascii colon and spaces", content: "[midori] : こんにちは", want: "こんにちは"},
		{name: "other separator is a tab", content: "[kuro]\t本文", want: "本文"},
		{name: "other separator is a CRLF", content: "[kuro]\r\n本文", want: "本文"},
		{name: "other separator is a full width colon", content: "[shiro]：報告", want: "報告"},
		{name: "other separator is an ascii colon", content: "[shiro]:報告", want: "報告"},
		{name: "other separator is a full width space", content: "[midori]　本文", want: "本文"},
		{name: "other separator is a newline", content: "[kuro]\n\n結論です", want: "結論です"},
		{name: "doubled other label", content: "[midori] [midori] 夕焼けです", want: "夕焼けです"},
		{name: "mixed other agents", content: "[midori] [shiro] [kuro] 夕焼けです", want: "夕焼けです"},
		{name: "every known name", content: "[mio] [shiro] [kuro] [midori] [aka] [ao] [kin] [gin] 本文", want: "本文"},
		{name: "full width space before the label", content: "　[mio]　こんにちは", want: "こんにちは"},

		// --- 他のラベルが区切りなしで続くものは残す
		{name: "relay phrase stays (other agent, no separator)", content: "[shiro]からの報告です", want: "[shiro]からの報告です"},
		{name: "relay phrase stays (other agent mio, generated by shiro)", self: SpeakerShiro, content: "[mio]は次のとおり答えました", want: "[mio]は次のとおり答えました"},
		{name: "other label glued to body stays", content: "[midori]本文", want: "[midori]本文"},
		{name: "other label glued to body stays (upper case)", content: "[MIDORI]本文", want: "[MIDORI]本文"},
		{name: "other labels glued together stay", content: "[midori][midori]夕焼けです", want: "[midori][midori]夕焼けです"},
		{name: "other label glued to another label stays", content: "[shiro][mio] 本文", want: "[shiro][mio] 本文"},
		{name: "second other label glued to body stays", content: "[midori] [midori]夕焼けです", want: "[midori]夕焼けです"},
		{name: "nbsp is not a separator", self: SpeakerShiro, content: "[mio] 本文", want: "[mio] 本文"},

		// --- 自分のラベルと他のラベルが混ざる場合は、先頭から順に判定する
		{name: "self glued then other with separator", content: "[mio][shiro] 本文", want: "本文"},
		{name: "self with separator then other glued stays", content: "[mio] [shiro]からの報告です", want: "[shiro]からの報告です"},
		{name: "other glued to self label stays", content: "[shiro][mio]本文", want: "[shiro][mio]本文"},
		{name: "self glued twice", self: SpeakerMidori, content: "[midori][midori]夕焼けです", want: "夕焼けです"},
		{name: "second self label glued to body", self: SpeakerMidori, content: "[midori] [midori]夕焼けです", want: "夕焼けです"},

		// --- ラベルだけの応答
		{name: "label only (self)", content: "[mio]", want: ""},
		{name: "label only (other)", content: "[midori]", want: ""},
		{name: "label only with spaces", content: "  [midori]  ", want: ""},
		{name: "label only with colon", content: "[midori]：", want: ""},
		{name: "doubled label only without trailing separator", content: "[midori] [midori]", want: ""},
		{name: "doubled label only", content: " [midori] [midori] \n", want: ""},
		{name: "self labels only, glued", self: SpeakerMidori, content: "[midori][midori]", want: ""},
		{name: "other labels only, glued, stay", content: "[midori][midori]", want: "[midori][midori]"},

		// --- 空
		{name: "empty", content: "", want: ""},
		{name: "whitespace only", content: " 　\n", want: ""},
		{name: "no label is trimmed only", content: "  こんにちは  ", want: "こんにちは"},

		// --- 変えないもの
		{name: "embedded label stays", content: "引用: [mio] こんにちは", want: "引用: [mio] こんにちは"},
		{name: "label after body stays", content: "こんにちは [midori] です", want: "こんにちは [midori] です"},
		{name: "unknown bracket stays", content: "[注] 補足です", want: "[注] 補足です"},
		{name: "unknown name stays", content: "[someone] 補足です", want: "[someone] 補足です"},
		{name: "unknown bracket before known label stays", content: "[注] [midori] 補足です", want: "[注] [midori] 補足です"},
		{name: "known label then unknown bracket", content: "[midori] [注] 補足です", want: "[注] 補足です"},
		{name: "partial label stays", content: "[mid", want: "[mid"},
		{name: "kelvin sign is not k", content: "[Kin] 本文", want: "[Kin] 本文"},
		{name: "body colon is kept", content: "[mio] 結論: 実行します", want: "結論: 実行します"},

		// --- 生成した Agent の指定
		{name: "legacy alias wild is midori", self: Speaker("wild"), content: "[midori]本文", want: "本文"},
		{name: "legacy alias heavy is kuro", self: Speaker("heavy"), content: "[kuro]本文", want: "本文"},
		{name: "speaker name is case-insensitive", self: Speaker("Midori"), content: "[midori]本文", want: "本文"},
		{name: "unknown speaker label is its own self label", self: Speaker("custom"), content: "[custom]本文", want: "本文"},
		{name: "unknown speaker leaves known labels to the separator rule", self: Speaker("custom"), content: "[mio]本文", want: "[mio]本文"},
		{name: "empty speaker uses the separator rule only", self: Speaker(" "), content: "[mio]本文", want: "[mio]本文"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			// 空の self は mio として扱うケースと、空白の self（指定なし）を区別する。
			speaker := tt.self
			if speaker == "" {
				speaker = SpeakerMio
			}
			if got := StripLeadingSpeakerLabels(tt.content, speaker); got != tt.want {
				t.Fatalf("StripLeadingSpeakerLabels(%q, %q) = %q, want %q", tt.content, speaker, got, tt.want)
			}
		})
	}
}

// 履歴へ入れる `[speaker] msg` の形式を作る RecallPack.ToPromptMessages と、
// StripLeadingSpeakerLabels は逆変換でなければならない（形式のownerが同じpackage）。
// どの Agent が生成しても（自分のラベルでも他の Agent のラベルでも）、履歴の形式は取り除ける。
func TestStripLeadingSpeakerLabelsInvertsRecallPackHistoryFormat(t *testing.T) {
	speakers := []Speaker{SpeakerMio, SpeakerShiro, SpeakerKuro, SpeakerMidori, Speaker("heavy"), Speaker("wild")} // 旧別名は canonical 名のラベルになる
	pack := &RecallPack{}
	for _, speaker := range speakers {
		pack.ShortContext = append(pack.ShortContext, Message{Speaker: speaker, Msg: "本文です"})
	}
	assistant := 0
	for _, message := range pack.ToPromptMessages() {
		if message.Role != "assistant" {
			continue
		}
		assistant++
		canonical, _ := CanonicalChatAgentSpeaker(pack.ShortContext[assistant-1].Speaker)
		if want := "[" + string(canonical) + "] 本文です"; message.Content != want {
			t.Fatalf("history format changed: %q, want %q", message.Content, want)
		}
		for _, generator := range []Speaker{SpeakerMio, SpeakerShiro, SpeakerKuro, SpeakerMidori} {
			if got := StripLeadingSpeakerLabels(message.Content, generator); got != "本文です" {
				t.Fatalf("Strip(%q, %q) = %q", message.Content, generator, got)
			}
		}
	}
	if assistant != len(speakers) {
		t.Fatalf("assistant history messages = %d, want %d", assistant, len(speakers))
	}
}

func TestAgentLabelNamesCoverEverySpeakerConstant(t *testing.T) {
	names := map[string]bool{}
	for _, name := range AgentLabelNames() {
		if name != strings.ToLower(name) || strings.TrimSpace(name) == "" {
			t.Fatalf("label name %q must be a non-empty lower-case name", name)
		}
		names[name] = true
	}
	for _, speaker := range []Speaker{SpeakerMio, SpeakerShiro, SpeakerKuro, SpeakerMidori, SpeakerAka, SpeakerAo, SpeakerKin, SpeakerGin} {
		if !names[string(speaker)] {
			t.Errorf("AgentLabelNames() is missing %q", speaker)
		}
	}
	for _, role := range []Speaker{SpeakerUser, SpeakerSystem, SpeakerTool, SpeakerMemory} {
		if names[string(role)] {
			t.Errorf("AgentLabelNames() must not contain non-Agent speaker %q", role)
		}
	}
	// 履歴に `[speaker]` として入る名前（canonical 名）は全て除去対象。
	for _, speaker := range []Speaker{SpeakerMio, SpeakerShiro, SpeakerKuro, SpeakerMidori, Speaker("heavy"), Speaker("wild")} {
		if canonical, ok := CanonicalChatAgentSpeaker(speaker); ok && !names[string(canonical)] {
			t.Errorf("history label %q is not a known label name", canonical)
		}
	}
}

type streamRecorder struct {
	tokens []string
}

func (r *streamRecorder) next(token string) { r.tokens = append(r.tokens, token) }
func (r *streamRecorder) text() string      { return strings.Join(r.tokens, "") }

func runLabelStream(self Speaker, tokens []string) *streamRecorder {
	rec := &streamRecorder{}
	callback, flush := NewSpeakerLabelStreamFilter(rec.next, self)
	for _, token := range tokens {
		callback(token)
	}
	flush()
	return rec
}

