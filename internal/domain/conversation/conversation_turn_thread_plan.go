package conversation

import modulecore "github.com/Nyukimin/RenCrow_CORE/modules/core"

// ConversationTurnThreadIdentity is the tuple assigned to a conversation turn.
type ConversationTurnThreadIdentity struct {
	ID   modulecore.ThreadID
	Seq  modulecore.ThreadSeq
	Kind modulecore.ThreadKind
}

// ConversationTurnActiveThreadState is the current L1 thread state used to
// plan the next accepted turn. The planner validates its identity and count.
type ConversationTurnActiveThreadState struct {
	Thread       ConversationTurnThreadIdentity
	Domain       string
	MessageCount int64
}

// ConversationTurnThreadPlanInput contains only the state and request fields
// that affect a turn's thread assignment. NewThreadID is generated by the
// caller so planning remains deterministic and side-effect free.
type ConversationTurnThreadPlanInput struct {
	Active      *ConversationTurnActiveThreadState
	Boundary    bool
	Domain      string
	NewThreadID modulecore.ThreadID
}

// ConversationTurnThreadPlan is the thread assignment and resulting active
// message count/domain for one accepted conversation turn.
type ConversationTurnThreadPlan struct {
	Thread       ConversationTurnThreadIdentity
	ClosedThread ConversationTurnThreadIdentity
	MessageCount int64
	Domain       string
}

// PlanConversationTurnThread assigns a turn to the current thread or starts a
// new one when the request declares a boundary or the message limit is reached.
func PlanConversationTurnThread(input ConversationTurnThreadPlanInput) (ConversationTurnThreadPlan, error) {
	domain := input.Domain
	if input.Active == nil {
		if err := input.NewThreadID.Validate(); err != nil {
			return ConversationTurnThreadPlan{}, invalidConversationTurn("new thread identity is invalid")
		}
		return ConversationTurnThreadPlan{
			Thread: ConversationTurnThreadIdentity{
				ID:   input.NewThreadID,
				Seq:  1,
				Kind: ThreadKindUserConversation,
			},
			MessageCount: 2,
			Domain:       domain,
		}, nil
	}

	active := *input.Active
	if active.Thread.ID.Validate() != nil || active.Thread.Seq.Validate() != nil || active.Thread.Kind.Validate() != nil ||
		active.MessageCount < 0 || active.MessageCount > MaxConversationProjectionThreadMessages {
		return ConversationTurnThreadPlan{}, invalidConversationTurn("active thread is invalid")
	}
	if domain == "" {
		domain = active.Domain
	}

	if input.Boundary || active.MessageCount+2 > MaxConversationProjectionThreadMessages {
		const maxThreadSeq = modulecore.ThreadSeq(1<<63 - 1)
		if active.Thread.Seq >= maxThreadSeq {
			return ConversationTurnThreadPlan{}, invalidConversationTurn("thread sequence overflow")
		}
		if err := input.NewThreadID.Validate(); err != nil {
			return ConversationTurnThreadPlan{}, invalidConversationTurn("new thread identity is invalid")
		}
		return ConversationTurnThreadPlan{
			Thread: ConversationTurnThreadIdentity{
				ID:   input.NewThreadID,
				Seq:  active.Thread.Seq + 1,
				Kind: active.Thread.Kind,
			},
			ClosedThread: active.Thread,
			MessageCount: 2,
			Domain:       domain,
		}, nil
	}

	return ConversationTurnThreadPlan{
		Thread:       active.Thread,
		MessageCount: active.MessageCount + 2,
		Domain:       domain,
	}, nil
}
