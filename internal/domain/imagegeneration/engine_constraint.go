package imagegeneration

import (
	"regexp"
	"strings"
)

// EngineConstraint identifies an engine explicitly requested for a normal
// image-generation request. ImageGen is recognized here only so the normal
// RenCrow_Image route can reject it; its separate CodexExe exception is not
// represented by this contract.
type EngineConstraint string

const (
	EngineConstraintComfyUI  EngineConstraint = "comfyui"
	EngineConstraintForgeNeo EngineConstraint = "forge-neo"
	EngineConstraintImageGen EngineConstraint = "ImageGen"
)

const (
	EngineComfyUI  = string(EngineConstraintComfyUI)
	EngineForgeNeo = string(EngineConstraintForgeNeo)
)

var (
	engineSelectionPattern  = regexp.MustCompile(`(?i)(comfyui|forge[\s_-]*neo|image[\s_-]*gen)(\s*(で|を使(って|い)|を使用して|を利用して|を指定して|にして)|\s+(for|to|with|using)\b)`)
	engineUsagePattern      = regexp.MustCompile(`(?i)(use|using|via|with)\s+(comfyui|forge[\s_-]*neo|image[\s_-]*gen)\b`)
	engineGenerationPattern = regexp.MustCompile(`(?i)(comfyui|forge[\s_-]*neo|image[\s_-]*gen)\s*(の\s*)?(画像|イラスト|絵|image)\s*(を\s*)?(生成|描画|generate|draw)`)
)

// IsBareEngineRequest recognizes only the short canonical forms that explicitly
// ask for an image to be generated by a named engine.
func IsBareEngineRequest(message string) bool {
	message = strings.TrimRight(strings.TrimSpace(message), ".!。！")
	message = strings.ToLower(strings.TrimSpace(message))
	switch message {
	case "画像をcomfyuiで", "画像をforge neoで", "画像をforge-neoで", "画像をforgeneoで", "画像をimagegenで", "画像をimage genで":
		return true
	default:
		return false
	}
}

// ParseEngineConstraint returns an explicitly selected engine. A mere engine
// mention is not sufficient: the message must use it as the generation target.
func ParseEngineConstraint(message string) (EngineConstraint, bool) {
	trimmed := strings.TrimSpace(message)
	if trimmed == "" {
		return "", false
	}
	var selected EngineConstraint
	matchedConstraint := false
	for _, match := range engineSelectionPattern.FindAllStringSubmatch(trimmed, -1) {
		if len(match) >= 2 {
			matchedConstraint = true
			if !mergeEngineConstraint(&selected, match[1]) {
				return "", true
			}
		}
	}
	for _, match := range engineUsagePattern.FindAllStringSubmatch(trimmed, -1) {
		if len(match) >= 3 {
			matchedConstraint = true
			if !mergeEngineConstraint(&selected, match[2]) {
				return "", true
			}
		}
	}
	for _, match := range engineGenerationPattern.FindAllStringSubmatch(trimmed, -1) {
		if len(match) >= 2 {
			matchedConstraint = true
			if !mergeEngineConstraint(&selected, match[1]) {
				return "", true
			}
		}
	}
	return selected, matchedConstraint
}

func mergeEngineConstraint(selected *EngineConstraint, mention string) bool {
	engine, ok := engineFromMention(mention)
	if !ok || (*selected != "" && *selected != engine) {
		return false
	}
	*selected = engine
	return true
}

func engineFromMention(mention string) (EngineConstraint, bool) {
	normalized := strings.ToLower(strings.NewReplacer(" ", "", "_", "", "-", "").Replace(mention))
	switch normalized {
	case "comfyui":
		return EngineConstraintComfyUI, true
	case "forgeneo":
		return EngineConstraintForgeNeo, true
	case "imagegen":
		return EngineConstraintImageGen, true
	default:
		return "", false
	}
}
